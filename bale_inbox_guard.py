@app_v3.app.after_request
def inject_bale_discard_ui(response):
    try:
        if request.path in {"/", "/index.html"} and response.mimetype == "text/html":
            response.direct_passthrough = False
            body = response.get_data(as_text=True)
            if "/bale-discard-ui.js" not in body:
                position = body.lower().find("</head>")
                if position >= 0:
                    tag = '<script src="/bale-discard-ui.js?v=20260831-1"></script>'
                    body = body[:position] + tag + body[position:]
                    response.set_data(body)
                    response.headers["Content-Length"] = str(len(response.get_data()))
            response.headers["Cache-Control"] = "no-store, max-age=0"
    except Exception as exc:
        app_v3.logger.warning("bale_discard_ui_inject_failed detail=%s", str(exc)[:200])
    return response
